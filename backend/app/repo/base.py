"""Storage-agnostic data access. Posts, images, etc. are plain dicts with DB column names.

Every post query is scoped by user_id because the service-role connection bypasses RLS.
`update_post(..., expected=...)` is a compare-and-set on status: it returns None when the
row's status is no longer in `expected`, which is how double submits get a 409.
"""
from collections.abc import Iterable
from typing import Protocol


class Repo(Protocol):
    # posts
    def create_post(self, data: dict) -> dict: ...
    def get_post(self, user_id: str, post_id: str) -> dict | None: ...
    def list_posts(self, user_id: str, status: str | None = None) -> list[dict]: ...
    def update_post(
        self, user_id: str, post_id: str, changes: dict, expected: Iterable[str] | None = None
    ) -> dict | None: ...
    def delete_post(self, user_id: str, post_id: str, expected: Iterable[str]) -> bool: ...
    def claim_due_scheduled(self, now_iso: str) -> list[dict]: ...
    def fail_stale_generating(self, before_iso: str, message: str) -> int: ...

    # images
    def add_image(self, post_id: str, source: str, storage_path: str, public_url: str) -> dict: ...
    def list_images(self, post_id: str) -> list[dict]: ...

    # publications (one row per post + platform)
    def list_publications(self, post_id: str) -> list[dict]: ...
    def upsert_publication(self, post_id: str, platform: str, changes: dict) -> dict: ...

    # social accounts
    def list_accounts(self, user_id: str) -> list[dict]: ...
    def get_account(self, user_id: str, platform: str) -> dict | None: ...
    def upsert_account(self, user_id: str, platform: str, data: dict) -> dict: ...
    def delete_account(self, user_id: str, platform: str) -> bool: ...

    # settings / feedback
    def get_settings(self, user_id: str) -> dict | None: ...
    def upsert_settings(self, user_id: str, data: dict) -> dict: ...
    def add_feedback(self, user_id: str, post_id: str, rating: str) -> dict: ...
